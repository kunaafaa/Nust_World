/**
 * npm run menus: re-read https://nustcafe.vercel.app and rewrite data/menus/<cafeId>.json
 * (+ docs/menu-notes.md). Order of preference per cafe:
 *   1. public API   https://nustcafe.vercel.app/api/menu/<id>   (JSON only; today it does not exist)
 *   2. the cafe's public JS chunk referenced by the site's main bundle (what the page itself renders from)
 * Nothing is invented or rounded. No keys, no logins, no private URLs.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import {
  buildMenu,
  menuNotes,
  parseCafeChunk,
  parseCafeList,
  rawFromApi,
  type Menu,
  type RawItem,
} from './lib/menus';

const BASE = process.env.NUSTCAFE_URL ?? 'https://nustcafe.vercel.app';
const ROOT = path.resolve(__dirname, '..');

async function get(url: string) {
  const r = await fetch(url, { headers: { 'user-agent': 'nust-world-menu-sync' } });
  return r;
}

async function main() {
  const home = await (await get(BASE + '/')).text();
  const script = home.match(/<script[^>]+src="(\/assets\/[^"]+\.js)"/)?.[1];
  if (!script) throw new Error('could not find the main bundle on the home page');
  const bundleUrl = BASE + script;
  const bundle = await (await get(bundleUrl)).text();
  const cafes = parseCafeList(bundle);
  if (!cafes.length) throw new Error('no cafes found in the main bundle (site changed?)');

  const dir = path.join(ROOT, 'data', 'menus');
  mkdirSync(dir, { recursive: true });
  const now = new Date().toISOString();
  const menus: Menu[] = [];
  const problems: string[] = [];

  for (const c of cafes) {
    let raw: RawItem[] | null = null;
    let source = '';
    try {
      const r = await get(`${BASE}/api/menu/${c.id}`);
      if ((r.headers.get('content-type') ?? '').includes('json')) {
        raw = rawFromApi(await r.json());
        if (raw) source = `${BASE}/api/menu/${c.id}`;
      }
    } catch {
      /* no API: fall through */
    }
    if (!raw) {
      if (!c.chunk) {
        problems.push(`${c.id}: no menu chunk found`);
        continue;
      }
      const url = `${BASE}/assets/${c.chunk}`;
      const r = await get(url);
      if (!r.ok) {
        problems.push(`${c.id}: ${url} -> HTTP ${r.status}`);
        continue;
      }
      raw = parseCafeChunk(await r.text());
      source = url;
    }
    const menu = buildMenu({ cafeId: c.id, name: c.name, source, updatedAt: now }, raw);
    menus.push(menu);
    writeFileSync(path.join(dir, `${c.id}.json`), JSON.stringify(menu, null, 2) + '\n');
    const n = menu.categories.reduce((s, k) => s + k.items.length, 0);
    console.log(
      `${c.id.padEnd(14)} ${String(n).padStart(4)} items  ${menu.categories.length} categories  <- ${source}`,
    );
  }
  if (problems.length) console.warn('\nProblems:\n' + problems.join('\n'));

  // docs/menu-notes.md (generated part)
  const lines = [
    '# Menu notes',
    '',
    '_Generated by `npm run menus`; manual edits are overwritten on the next run._',
    '',
    `Source site: ${BASE} (main bundle ${bundleUrl}).`,
    '',
    '## Cafes read',
    '',
    '| id | site name | items | categories | read from |',
    '| --- | --- | --- | --- | --- |',
    ...menus.map(
      (m) =>
        `| ${m.cafeId} | ${m.name} | ${m.categories.reduce((s, k) => s + k.items.length, 0)} | ${m.categories.length} | ${m.source.replace(BASE, '')} |`,
    ),
    '',
    '## Things to look at',
    '',
  ];
  let any = false;
  for (const m of menus) {
    const notes = menuNotes(m);
    if (!notes.length) continue;
    any = true;
    lines.push(`### ${m.cafeId}`, '', ...notes.map((n) => `- ${n}`), '');
  }
  if (!any) lines.push('Nothing unusual found by the automatic checks.', '');
  lines.push(
    '## Fixed observations (about the source, not the data)',
    '',
    '- The site stores only `id, name, price, rating, category` per item. There are **no descriptions, no variants, no tags and no availability flag**. Every item is therefore written with `available: true` (the site shows every item as orderable) and no `description`/`variants`/`tags`.',
    '- `rating` is `0` for every item and is not copied.',
    '- Category names are copied exactly as the site stores them (for example `RollParatha`, written without a space). The site shows them the same way. They are not reformatted.',
    '- Category order is the order of first appearance in the data. The site itself lists its filter pills alphabetically and shows items in data order.',
    '- Prices are whole rupees (PKR) exactly as shown. The site prints them as `Rs. <price>`.',
    '- `updatedAt` is when this script last read the site, not a date published by the cafe.',
    '',
  );
  writeFileSync(path.join(ROOT, 'docs', 'menu-notes.md'), lines.join('\n'));
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
