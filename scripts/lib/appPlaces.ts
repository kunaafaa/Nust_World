/** The place list exactly as the app builds it (App.tsx): OSM + landmarks, topo merge, hostel placement. */
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { landmarks } from '../../src/data/landmarks';
import { buildCampus } from '../../src/lib/campus';
import { applyHostelPlacement } from '../../src/lib/hostelPlacement';
import type { RawOsm } from '../../src/lib/osm';
import { applyTopoMerge, type TopoMergeFile, type TopoTreesFile } from '../../src/lib/topoMerge';
import { REVIEW_EXCLUDED_CATEGORIES } from '../../src/lib/reviews/types';

const ROOT = path.resolve(__dirname, '..', '..');
const json = <T>(p: string) => JSON.parse(readFileSync(path.join(ROOT, p), 'utf8')) as T;

export function appPlaces() {
  const osm = json<RawOsm>('public/data/nust-full.geojson');
  return applyHostelPlacement(
    applyTopoMerge(
      buildCampus({ osm, landmarks }),
      json<TopoMergeFile>('public/data/topo-merge.json'),
      json<TopoTreesFile>('public/data/topo-trees.json'),
    ),
  ).places;
}

/** Ids of places that never take reviews (prayer, medical), sorted. */
export function excludedPlaceIds(): string[] {
  return appPlaces()
    .filter((p) => REVIEW_EXCLUDED_CATEGORIES.includes(p.category))
    .map((p) => p.id)
    .sort();
}

export function excludedPlacesSql(ids: string[]): string {
  return [
    "-- Generated by `npm run reviews-seed` from the app's place list: every prayer and medical place.",
    '-- The database refuses reviews for these ids (public.excluded_places). Re-run after data changes.',
    'insert into public.excluded_places (place_id) values',
    ids.map((id) => `  ('${id.replace(/'/g, "''")}')`).join(',\n'),
    'on conflict (place_id) do nothing;',
    '',
  ].join('\n');
}
